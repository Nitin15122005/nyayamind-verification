PARTIALS = ["figures.csv", "diagrams.csv", "tables.csv"]


def repo_commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "HEAD"], cwd=C.REPO_ROOT,
                              capture_output=True, text=True, check=True).stdout.strip()
    except Exception:
        return "unknown"


def load_partials() -> list[dict]:
    rows: list[dict] = []
    for name in PARTIALS:
        p = C.BUILD_STATE / name
        if p.exists():
            rows += C.read_csv(p)
    return rows


def build_manifest(rows: list[dict]) -> None:
    fields = ["artifact_id", "artifact_type", "filename", "ppt_variant", "title", "purpose",
              "metric_contract_csv", "source_artifact", "dataset", "n", "system_model_names",
              "baseline_or_modified", "fresh_or_historical", "evidence_grade", "caveat",
              "generation_script"]
    C.write_csv(C.PKG_DIR / "VISUALIZATION_MANIFEST.csv", fields, rows)
    print(f"  wrote VISUALIZATION_MANIFEST.csv ({len(rows)} artifacts)")


