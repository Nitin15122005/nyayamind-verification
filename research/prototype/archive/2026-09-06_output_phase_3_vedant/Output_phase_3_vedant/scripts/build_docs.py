        "F23 component coverage |",
        "| HISTORICAL | Cited from a committed prior-session artifact and NOT re-executed here | "
        "every GPU-dependent correction figure |",
        "| PROVISIONAL | Claude-generated labels, never lawyer-verified | **excluded from this "
        "package entirely** — see NOT_GENERATED_REGISTER.md |",
        "",
        "## Standing prohibitions honoured by every figure in this package",
        "",
