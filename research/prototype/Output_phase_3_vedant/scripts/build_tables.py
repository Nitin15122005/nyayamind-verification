def md_table(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c).replace("|", "\\|") for c in r) + " |")
    return "\n".join(out)


def emit(name: str, headers: list[str], rows: list[list[str]], title: str,
         purpose: str, sources: list[str], caveat: str, intro: str = "") -> None:
    csv_rows = [dict(zip(headers, r)) for r in rows]
    C.write_csv(C.OUT_TABLES / f"{name}.csv", headers, csv_rows)
    body = [f"# {title}", ""]
    if intro:
        body += [intro, ""]
    body += [md_table(headers, rows), "",
             "**Source artifacts:** " + "; ".join(sources), "",
             f"**Caveat:** {caveat}", "",
             "_Generated by `Output_phase_3_vedant/scripts/build_tables.py` from the locked "
             "metric contracts in `Output_phase_3_vedant/metrics/`. Every value traces to a "
             "row of `METRIC_SOURCE_MAP.csv`._"]
    (C.OUT_TABLES / f"{name}.md").write_text("\n".join(body) + "\n", encoding="utf-8")
    TABLE_MANIFEST.append({
        "artifact_id": name.split("_")[0],
        "artifact_type": "table",
        "filename": f"tables/{name}.csv",
        "ppt_variant": f"tables/{name}.md",
        "title": title,
        "purpose": purpose,
        "metric_contract_csv": "; ".join(sources),
        "source_artifact": "; ".join(sources),
        "dataset": "see rows",
        "n": "see rows",
        "system_model_names": f"{C.BASELINE_NAME} vs {C.MODIFIED_NAME}",
        "baseline_or_modified": "baseline vs modified",
        "fresh_or_historical": "see rows",
        "evidence_grade": "see rows",
        "caveat": caveat,
        "generation_script": "Output_phase_3_vedant/scripts/build_tables.py",
    })
    print(f"  wrote tables/{name}.csv + .md ({len(rows)} rows)")


def f4(x) -> str:
    return f"{float(x):.4f}"


def pct1(x) -> str:
    return f"{100 * float(x):.1f}%"


